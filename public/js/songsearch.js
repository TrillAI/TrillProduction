/* Trill Tuner — Songs: the play-along library.
 *
 * One box, and it searches everything by song OR artist (or genre, or chords):
 * Hundreds of chord charts, artist profiles and technique lessons, all of it
 * stored in the app so it works with no connection at all. When there *is* a
 * connection it also asks the server for extra lyric matches, so the search gets
 * wider rather than breaking.
 *
 * Every result can be turned into something you can actually play: a chord
 * library for its key, a capo position, similar songs, a metronome setting, the
 * lyrics, or the whole thing inside the tab maker.
 */
(function () {
  'use strict';

  const SS = {};
  const els = {};
  const state = { query: '', level: 'any', tab: 'songs', online: null, artist: null };
  let lastResults = null;

  const LEVELS = [
    { id: 'any', label: 'Everything' },
    { id: 'beginner', label: 'Beginner (1–2)' },
    { id: 'mid', label: 'Intermediate (3)' },
    { id: 'hard', label: 'Advanced (4–5)' }
  ];
  const QUICK = [
    ['Songs for the first week', '3 chords'],
    ['Fingerstyle', 'fingerstyle'],
    ['Rock riffs', 'riff'],
    ['Blues', 'blues'],
    ['Jazz', 'jazz'],
    ['Capo songs', 'capo'],
    ['Open tunings', 'open tuning'],
    ['Hendrix', 'hendrix'],
    ['Fleetwood Mac', 'fleetwood mac'],
    ['Oasis', 'oasis'],
    ['The Beatles', 'beatles'],
    ['Songs with F', 'F']
  ];

  function levelOk(song) {
    if (state.level === 'any') return true;
    if (state.level === 'beginner') return song.level <= 2;
    if (state.level === 'mid') return song.level === 3;
    return song.level >= 4;
  }

  function el(tag, cls, text) {
    const n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    return n;
  }
  function setStatus(msg, cls) {
    if (!els.status) return;
    els.status.textContent = msg || '';
    els.status.className = 'ss-status' + (cls ? ' ' + cls : '');
  }

  function setTab(tab) {
    state.tab = tab;
    document.querySelectorAll('#ss-tabs .tab').forEach(b => b.classList.toggle('active', b.dataset.tab === tab));
    document.querySelectorAll('#view-songs .tabpane').forEach(p => p.classList.toggle('active', p.id === 'ss-pane-' + tab));
  }

  /* ---------------------------------------------------------------- */
  /* set list                                                          */
  /* ---------------------------------------------------------------- */
  function setlist() { return TT.store ? TT.store.get('setlist', []) : []; }
  function inSetlist(id) { return setlist().indexOf(id) >= 0; }
  function toggleSetlist(song) {
    let list = setlist();
    if (inSetlist(song.id)) list = list.filter(x => x !== song.id);
    else list.unshift(song.id);
    TT.store.set('setlist', list.slice(0, 60));
    renderSetlist();
    if (TT.app) TT.app.toast(inSetlist(song.id) ? '★ ' + song.title + ' saved to your set list' : song.title + ' removed from the set list');
  }
  function renderSetlist() {
    if (!els.setlist) return;
    els.setlist.innerHTML = '';
    const list = setlist().map(id => TT.catalog.songById(id)).filter(Boolean);
    if (!list.length) { els.setlist.innerHTML = '<span class="dim">Nothing saved yet — press ★ Save on any song.</span>'; return; }
    list.forEach(s => {
      const b = el('button', 'chip-s', s.title + ' · ' + s.artist);
      b.type = 'button';
      b.title = 'Key ' + s.key + ' · ' + s.bpm + ' BPM · ' + s.chords.join(' ') + ' — click for the play-along chart';
      b.addEventListener('click', () => openPlayAlong(s));
      els.setlist.appendChild(b);
    });
  }
  function copySetlist() {
    const list = setlist().map(id => TT.catalog.songById(id)).filter(Boolean);
    if (!list.length) { setStatus('Nothing in the set list yet.', 'err'); return; }
    const text = 'My Trill Tuner set list\n' + '='.repeat(24) + '\n' +
      list.map((s, i) => `${i + 1}. ${s.title} — ${s.artist}\n   Key ${s.key} · ${s.bpm} BPM · capo ${s.capo || 0} · ${s.chords.join(' ')}`).join('\n') +
      '\n\nGenerated by Trill Tuner.';
    copyText(text, 'Set list copied ✓');
  }
  function copyText(text, okMsg) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(() => setStatus(okMsg, 'ok'));
    } else {
      const ta = document.createElement('textarea');
      ta.value = text; document.body.appendChild(ta); ta.select();
      try { document.execCommand('copy'); setStatus(okMsg, 'ok'); } catch (e) { setStatus('Could not copy — select the text by hand.', 'err'); }
      ta.remove();
    }
  }

  /* ---------------------------------------------------------------- */
  /* results                                                           */
  /* ---------------------------------------------------------------- */
  function openPlayAlong(song) {
    if (TT.tablab) TT.tablab.openSong(song);
    TT.app.showView('maker');
    if (TT.app && TT.app.assist) TT.app.assist('Play-along chart for “' + song.title + '” — ' + song.key + ', ' + song.chords.join(' ') + '.');
  }
  function openLyrics(song) {
    TT.app.showView('lyrics');
    const box = document.getElementById('lyr-q');
    if (box) box.value = song.title + ' ' + song.artist;
    if (TT.lyrics && TT.lyrics.search) TT.lyrics.search(song.title + ' ' + song.artist);
  }

  function songCard(s) {
    const card = el('div', 'song-card');
    const head = el('div', 'song-head');
    const t = el('div', 'song-title');
    t.innerHTML = `<b>${s.title}</b><span class="dim">${s.artist}</span>`;
    head.appendChild(t);
    const meta = el('div', 'song-meta');
    meta.innerHTML = `<span title="key">${s.key}</span><span title="tempo">${s.bpm} BPM</span>
      <span title="difficulty">${'★'.repeat(Math.max(1, Math.min(5, s.level)))}</span>
      ${s.capo ? `<span title="capo position">capo ${s.capo}</span>` : ''}`;
    head.appendChild(meta);
    card.appendChild(head);

    const chords = el('div', 'song-chords');
    s.chords.forEach(c => chords.appendChild(el('span', 'song-chord', c)));
    card.appendChild(chords);

    card.appendChild(el('div', 'song-prog', s.progression));
    if (s.notes) card.appendChild(el('div', 'song-notes', s.notes));

    const btns = el('div', 'row-btns');
    const b1 = el('button', 'btn btn-primary tiny', '🎸 Play-along chart');
    b1.type = 'button'; b1.addEventListener('click', () => openPlayAlong(s));
    btns.appendChild(b1);
    const b2 = el('button', 'btn btn-ghost tiny', '♪ Lyrics');
    b2.type = 'button'; b2.addEventListener('click', () => openLyrics(s));
    btns.appendChild(b2);
    const b3 = el('button', 'btn btn-ghost tiny', inSetlist(s.id) ? '★ Saved' : '☆ Save');
    b3.type = 'button'; b3.addEventListener('click', () => { toggleSetlist(s); b3.textContent = inSetlist(s.id) ? '★ Saved' : '☆ Save'; });
    btns.appendChild(b3);
    const favBtn = el('button', 'btn btn-ghost tiny', (TT.mine && TT.mine.isFav(s.id)) ? '♥ Favourite' : '♡ Favourite');
    favBtn.type = 'button';
    favBtn.addEventListener('click', () => {
      if (!TT.mine) return;
      const on = TT.mine.toggleSong(s.id);
      favBtn.textContent = on ? '♥ Favourite' : '♡ Favourite';
      TT.app.toast(on ? 'Added to My stuff ♥' : 'Removed from My stuff');
    });
    btns.appendChild(favBtn);
    const b4 = el('button', 'btn btn-ghost tiny', '♩ ' + s.bpm + ' BPM');
    b4.type = 'button';
    b4.addEventListener('click', () => {
      if (TT.metronome) { TT.metronome.setBpm(s.bpm); TT.metronome.start(); TT.app.showView('metronome'); }
    });
    btns.appendChild(b4);
    const b5 = el('button', 'btn btn-ghost tiny', '⧉ Copy chart');
    b5.type = 'button';
    b5.addEventListener('click', () => copyText(
      s.title + ' — ' + s.artist + '\nKey ' + s.key + ' · ' + s.bpm + ' BPM' + (s.capo ? ' · capo ' + s.capo : '') +
      '\nChords: ' + s.chords.join('  ') + '\n' + s.progression + (s.notes ? '\n\n' + s.notes : '') + '\n\n(Trill Tuner)',
      'Chart copied ✓'));
    btns.appendChild(b5);
    card.appendChild(btns);
    return card;
  }

  function artistCard(a) {
    const card = el('div', 'song-card artist-card');
    const head = el('div', 'song-head');
    head.innerHTML = `<div class="song-title"><b>${a.name}</b><span class="dim">${a.genres.join(' · ')}</span></div>`;
    card.appendChild(head);
    card.appendChild(el('div', 'song-notes', a.knownFor));
    if (a.signature) card.appendChild(el('div', 'song-prog', '🎚️ ' + a.signature));
    if (a.techniques && a.techniques.length) {
      const tech = el('div', 'chipwrap');
      a.techniques.forEach(t => tech.appendChild(el('span', 'chip-s', t)));
      card.appendChild(tech);
    }
    if (a.songs && a.songs.length) {
      const songs = el('div', 'chipwrap');
      a.songs.forEach(name => {
        const found = TT.catalog.SONGS.find(s => s.title.toLowerCase().indexOf(name.toLowerCase()) === 0 ||
          name.toLowerCase().indexOf(s.title.toLowerCase()) === 0);
        const b = el('button', 'chip-s', name);
        b.type = 'button';
        b.addEventListener('click', () => {
          if (found) openPlayAlong(found);
          else { if (els.q) els.q.value = name + ' ' + a.name; SS.search(els.q.value); }
        });
        songs.appendChild(b);
      });
      card.appendChild(songs);
    }
    const rig = el('div', 'row-btns');
    const b = el('button', 'btn btn-ghost tiny', '🎛️ Settings like this in the Rig');
    b.type = 'button';
    b.addEventListener('click', () => {
      TT.app.showView('rig');
      if (TT.rig && TT.rig.findSimilar) TT.rig.findSimilar(a.name);
      else TT.app.toast('Search the pedal list for: ' + a.techniques.slice(0, 3).join(', '));
    });
    rig.appendChild(b);
    card.appendChild(rig);
    return card;
  }

  function lessonCard(l) {
    const card = el('div', 'song-card lesson-card');
    const head = el('div', 'song-head');
    head.innerHTML = `<div class="song-title"><b>${l.title}</b><span class="dim">${l.skill} · level ${l.level}/5</span></div>`;
    card.appendChild(head);
    card.appendChild(el('div', 'song-notes', l.description));
    if (l.how && l.how.length) {
      const ol = el('ol', 'lesson-how');
      l.how.forEach(h => ol.appendChild(el('li', null, h)));
      card.appendChild(ol);
    }
    const songs = el('div', 'chipwrap');
    (l.songs || []).forEach(name => {
      const found = TT.catalog.SONGS.find(s => s.title.toLowerCase().indexOf(name.toLowerCase()) === 0 ||
        name.toLowerCase().indexOf(s.title.toLowerCase()) === 0);
      const b = el('button', 'chip-s', '▶ ' + name);
      b.type = 'button';
      b.addEventListener('click', () => {
        if (found) openPlayAlong(found);
        else { if (els.q) els.q.value = name; SS.search(name); }
      });
      songs.appendChild(b);
    });
    card.appendChild(songs);
    const row = el('div', 'row-btns');
    const b = el('button', 'btn btn-ghost tiny', '📚 Open in Learn');
    b.type = 'button';
    b.addEventListener('click', () => TT.app.showView('learn'));
    row.appendChild(b);
    card.appendChild(row);
    return card;
  }

  function renderResults(res) {
    lastResults = res;
    if (els.countSongs) els.countSongs.textContent = res.songs.length;
    if (els.countArtists) els.countArtists.textContent = res.artists.length;
    if (els.countLessons) els.countLessons.textContent = res.lessons.length;

    const songs = res.songs.filter(songCard => levelOk(songCard));
    els.songs.innerHTML = '';
    if (!songs.length) els.songs.innerHTML = '<div class="dim">No songs matched. Try an artist name, a genre (“blues”, “fingerstyle”), or chords you know (“Am F C G”).</div>';
    songs.forEach(s => els.songs.appendChild(songCard(s)));

    els.artists.innerHTML = '';
    if (!res.artists.length) els.artists.innerHTML = '<div class="dim">No artist profiles matched.</div>';
    res.artists.forEach(a => els.artists.appendChild(artistCard(a)));

    els.lessons.innerHTML = '';
    if (!res.lessons.length) els.lessons.innerHTML = '<div class="dim">No lessons matched.</div>';
    res.lessons.forEach(l => els.lessons.appendChild(lessonCard(l)));

    setTab(res.songs.length ? 'songs' : (res.artists.length ? 'artists' : (res.lessons.length ? 'lessons' : state.tab)));
  }

  /* the online half: same question, asked of the server, merged in quietly */
  async function onlineSearch(q) {
    els.online.innerHTML = '<div class="dim">Checking lyric databases for anything the library does not already have…</div>';
    try {
      const r = await fetch('/api/songs?q=' + encodeURIComponent(q));
      const j = await r.json();
      if (!j.ok) throw new Error(j.error || 'no results');
      const list = (j.results || []);
      state.online = list;
      els.online.innerHTML = '';
      if (!list.length) { els.online.innerHTML = '<div class="dim">Nothing extra online for that search — the library above is everything.</div>'; return; }
      list.slice(0, 24).forEach(hit => {
        const row = el('div', 'song-card');
        const head = el('div', 'song-head');
        head.innerHTML = `<div class="song-title"><b>${hit.title}</b><span class="dim">${hit.artist || 'unknown artist'}</span></div>`;
        row.appendChild(head);
        if (hit.album) row.appendChild(el('div', 'song-prog', hit.album));
        const btns = el('div', 'row-btns');
        const bl = el('button', 'btn btn-primary tiny', '♪ Lyrics');
        bl.type = 'button';
        bl.addEventListener('click', () => {
          TT.app.showView('lyrics');
          const box = document.getElementById('lyr-q');
          if (box) box.value = (hit.title || '') + ' ' + (hit.artist || '');
          if (TT.lyrics && TT.lyrics.search) TT.lyrics.search((hit.title || '') + ' ' + (hit.artist || ''));
        });
        btns.appendChild(bl);
        const bc = el('button', 'btn btn-ghost tiny', '⟳ Find the chords myself');
        bc.type = 'button';
        bc.addEventListener('click', () => {
          if (TT.tablab) TT.tablab.openSong({ title: hit.title, artist: hit.artist || '', key: 'C', bpm: 100, chords: [], level: 2, notes: 'Load the audio into the Tab maker and it will read the chords off the recording.' });
          TT.app.showView('maker');
          TT.app.toast('Drop the song file into the Tab maker — it will read the chords, key and tempo itself.');
        });
        btns.appendChild(bc);
        row.appendChild(btns);
        els.online.appendChild(row);
      });
    } catch (e) {
      els.online.innerHTML = `<div class="dim">The built-in library above is the full local collection — ${TT.catalog.counts.songs} songs, ${TT.catalog.counts.artists} artists and ${TT.catalog.counts.lessons} lessons, all on this device.</div>`;
    }
  }

  /* ---------------------------------------------------------------- */
  SS.search = function (q) {
    state.query = (q || '').trim();
    if (els.q && els.q.value !== q) els.q.value = state.query;
    const res = TT.catalog.search(state.query, { cap: 100 });
    renderResults(res);
    const plural = (n, word) => n + ' ' + word + (n === 1 ? '' : 's');
    let line = '';
    if (state.query) {
      line = plural(res.songs.length, 'song') + ' · ' + plural(res.artists.length, 'artist') + ' · ' +
        plural(res.lessons.length, 'lesson') + ' for “' + state.query + '”';
      if (res.songs.some(x => x.chordMatch)) line += ' — including songs that use those chords';
    }
    setStatus(line, '');
    /* only ask the server when there IS a server to ask — PWA/APK file:// the
     * built-in library is the whole answer, and it is not a broken state */
    const canAskServer = navigator.onLine && location.protocol.indexOf('http') === 0;
    if (state.query.length >= 2 && canAskServer) onlineSearch(state.query);
    else if (els.online) els.online.innerHTML = '<div class="dim">' + (canAskServer
      ? 'Search with two or more letters and this will also check online lyric databases.'
      : 'Using the built-in library on this device — ' + TT.catalog.counts.songs + ' songs, all searchable.') + '</div>';
  };

  SS.openSong = function (id) {
    const s = TT.catalog.songById(id);
    if (!s) return;
    openPlayAlong(s);
  };

  SS.init = function () {
    if (SS._ready) return;
    SS._ready = true;
    els.form = document.getElementById('ss-form');
    els.q = document.getElementById('ss-q');
    els.status = document.getElementById('ss-status');
    els.quick = document.getElementById('ss-quick');
    els.level = document.getElementById('ss-level');
    els.songs = document.getElementById('ss-songs');
    els.artists = document.getElementById('ss-artists');
    els.lessons = document.getElementById('ss-lessons');
    els.online = document.getElementById('ss-online');
    els.setlist = document.getElementById('ss-setlist');
    els.countSongs = document.getElementById('ss-n-songs');
    els.countArtists = document.getElementById('ss-n-artists');
    els.countLessons = document.getElementById('ss-n-lessons');
    els.btnCopySet = document.getElementById('ss-btn-copy-set');
    els.btnClearSet = document.getElementById('ss-btn-clear-set');

    if (els.form) els.form.addEventListener('submit', e => { e.preventDefault(); SS.search(els.q.value); });
    if (els.q) {
      els.q.addEventListener('input', () => {
        clearTimeout(SS._t);
        SS._t = setTimeout(() => SS.search(els.q.value), 180);
      });
    }
    if (els.quick) {
      QUICK.forEach(([label, query]) => {
        const b = el('button', 'chip-s', label);
        b.type = 'button';
        b.addEventListener('click', () => SS.search(query));
        els.quick.appendChild(b);
      });
    }
    if (els.level) {
      LEVELS.forEach(l => {
        const b = el('button', 'seg-btn' + (l.id === 'any' ? ' active' : ''), l.label);
        b.type = 'button';
        b.addEventListener('click', () => {
          state.level = l.id;
          els.level.querySelectorAll('.seg-btn').forEach(x => x.classList.toggle('active', x.textContent === l.label));
          if (lastResults) renderResults(lastResults);
        });
        els.level.appendChild(b);
      });
    }
    document.querySelectorAll('#ss-tabs .tab').forEach(b => b.addEventListener('click', () => setTab(b.dataset.tab)));
    if (els.btnCopySet) els.btnCopySet.addEventListener('click', copySetlist);
    if (els.btnClearSet) els.btnClearSet.addEventListener('click', () => { TT.store.set('setlist', []); renderSetlist(); setStatus('Set list cleared.'); });
    renderSetlist();
    if (els.online) els.online.innerHTML = '<div class="dim">Search with two or more letters and this will also check online lyric databases.</div>';
    const blurb = document.getElementById('ss-blurb');
    if (blurb) blurb.textContent = TT.catalog.counts.songs + ' play-along songs in the library, searchable by title, artist, genre or chords.';
    /* open on something useful rather than an empty page */
    SS.search('beginner');
  };

  SS.state = state;
  window.TT = window.TT || {};
  window.TT.songs = SS;
})();
